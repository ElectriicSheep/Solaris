"""Generate adv_map.c / adv_map.h: ADV_GroupSoc numbered fields <-> array (solaris_can.h)."""
L = ['/* adv_map.c - generated by tools/genAdvMap.py. Do not edit. */', '#include "adv_map.h"', '',
     'void map_group_soc(struct solaris_can_adv_group_soc_t *m, int mux, const double pct[16], const int avail[16]) {',
     '    m->adv_group_soc_mux = (uint8_t)mux;', '    switch (mux) {']
for mux in range(4):
    L.append(f'    case {mux}:')
    for j in range(4):
        i = 4 * mux + j
        L.append(f'        m->group_soc_{i:03d} = avail[{i}] ? solaris_can_adv_group_soc_group_soc_{i:03d}_encode(pct[{i}]) : 0x3FFF;')
    L.append('        break;')
L += ['    default: break;', '    }', '}']
open("adv_map.c", "w").write("\n".join(L) + "\n")
